#!/usr/bin/env bash
# Regenerates src/sys/generated.rs from the webgpu.h of the emdawnwebgpu port
# that Emscripten pins (emdawnwebgpu v20260423.175430 for Emscripten 6.0.9).
#
#   nix shell nixpkgs#rust-bindgen nixpkgs#emscripten --command \
#     crates/mln_wgpu_webgpu_h/gen_bindings.sh
#
# bindgen emits no functions when clang targets wasm32, so it runs for the
# host target. That is fine: without layout tests the type definitions are
# identical (webgpu.h uses fixed-size integers, size_t and pointers only).
# The #define constants (WGPU_STRLEN, ...) are written by hand in src/sys.rs,
# because they depend on the target's size_t.
#
# The functions are wrapped in `webgpu_functions! { ... }` (src/sys.rs): an
# extern block on Emscripten, panicking stubs elsewhere, so native builds
# type-check the backend without undefined wgpu* symbols.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export EM_CACHE="${EM_CACHE:-$(mktemp -d)}"
emcc_dir="$(dirname "$(readlink -f "$(command -v emcc)")")"
# Fetches the port into EM_CACHE if it isn't there yet.
echo 'int main(void){return 0;}' > "$EM_CACHE/port_probe.c"
emcc --use-port=emdawnwebgpu -c "$EM_CACHE/port_probe.c" -o "$EM_CACHE/port_probe.o"
pkg="$EM_CACHE/ports/emdawnwebgpu/emdawnwebgpu_pkg"
sysroot="$emcc_dir/../share/emscripten/cache/sysroot"
[ -d "$sysroot" ] || sysroot="$EM_CACHE/sysroot"
version="$(grep -o "v[0-9][0-9.]*" "$pkg/VERSION.txt" | head -1)"
raw="$(mktemp)"
bindgen "$pkg/webgpu/include/webgpu/webgpu.h" \
  --no-layout-tests --no-doc-comments --no-prepend-enum-name --use-core \
  --allowlist-function 'wgpu.*' --allowlist-type 'WGPU.*' --allowlist-var 'WGPU.*' \
  -o "$raw" -- -I"$pkg/webgpu/include" -isystem "$sysroot/include"
python3 -I - "$raw" "$here/src/sys/generated.rs" "$version" <<'PY'
import re, sys
raw, out, version = sys.argv[1:]
src = open(raw).read()
blocks = re.compile(r'unsafe extern "C" \{\n(.*?)\n\}\n', re.S)
functions = [m.group(1) for m in blocks.finditer(src)]
types = blocks.sub("", src).replace("/* automatically generated by rust-bindgen", "// Generated by rust-bindgen", 1)
types = types.replace(" */\n", "\n", 1)
header = (
    "// @generated by crates/mln_wgpu_webgpu_h/gen_bindings.sh from webgpu.h of\n"
    f"// emdawnwebgpu: {version}\n"
    "// Do not edit.\n\n"
)
open(out, "w").write(header + types.rstrip() + "\n\nwebgpu_functions! {\n" + "\n".join(functions) + "\n}\n")
PY
rm -f "$raw"
# The repository's formatting (rustfmt would reformat it through sys.rs anyway).
rustfmt --edition 2024 --config max_width=120,use_small_heuristics=Max "$here/src/sys/generated.rs"
echo "wrote $here/src/sys/generated.rs ($version)"
